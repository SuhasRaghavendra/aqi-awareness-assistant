#!/usr/bin/env python
"""
scripts/build_logbook_index.py
-------------------------------
Regenerates docs/logbook/INDEX.md from all NNN-*.md files in the logbook.

Extracts the title, date, phase, author, branch, and commit from the
YAML-like header block at the top of each entry.

Run automatically by ``make step-close`` or manually::

    python scripts/build_logbook_index.py
"""

from __future__ import annotations

import re
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parent.parent
_LOGBOOK_DIR = _REPO_ROOT / "docs" / "logbook"
_INDEX_PATH = _LOGBOOK_DIR / "INDEX.md"


def _extract_header(text: str) -> dict[str, str]:
    """Extract key fields from the logbook entry header."""
    info: dict[str, str] = {}

    # Title line: # Step NNN --- Title
    m = re.match(r"^# Step (\d+)\s+[^\w\s]+\s+(.+)$", text, re.MULTILINE)
    if m:
        info["step"] = m.group(1)
        info["title"] = m.group(2).strip()

    # Date/time line
    m = re.search(r"\*\*Date/time:\*\*\s*(.+)", text)
    if m:
        info["date"] = m.group(1).strip()

    # Phase
    m = re.search(r"\*\*Phase:\*\*\s*(\d+)", text)
    if m:
        info["phase"] = m.group(1).strip()

    # Author
    m = re.search(r"\*\*Author:\*\*\s*(.+?)\s+\*\*Reviewer", text)
    if m:
        info["author"] = m.group(1).strip()

    # Branch
    m = re.search(r"\*\*Branch / PR:\*\*\s*`?([^`\n]+)`?", text)
    if m:
        info["branch"] = m.group(1).strip()

    # Commit
    m = re.search(r"\*\*Git commit\(s\):\*\*\s*`?([a-f0-9]{7,40})`?", text)
    if m:
        info["commit"] = m.group(1)[:12]

    return info


def build_index() -> str:
    """Return the full INDEX.md content."""
    entries = sorted(_LOGBOOK_DIR.glob("[0-9][0-9][0-9]-*.md"))

    rows: list[str] = []
    for path in entries:
        text = path.read_text(encoding="utf-8")
        h = _extract_header(text)
        step = h.get("step", path.stem.split("-")[0])
        title = h.get("title", path.stem)
        date = h.get("date", "---")[:10]
        phase = h.get("phase", "---")
        author = h.get("author", "---")
        commit = h.get("commit", "---")
        link = f"[{path.name}]({path.name})"
        rows.append(f"| {step} | {date} | {title} | {phase} | {author} | `{commit}` | {link} |")

    header = (
        "# Logbook Index\n\n"
        "> Auto-generated by `scripts/build_logbook_index.py`. Do not edit manually.\n\n"
        "| Step | Date | Title | Phase | Author | Commit | Entry |\n"
        "|---|---|---|---|---|---|---|\n"
    )
    return header + "\n".join(rows) + "\n"


def main() -> None:
    _LOGBOOK_DIR.mkdir(parents=True, exist_ok=True)
    content = build_index()
    _INDEX_PATH.write_text(content, encoding="utf-8")
    n = len(list(_LOGBOOK_DIR.glob("[0-9][0-9][0-9]-*.md")))
    print(f"[OK] INDEX.md rebuilt - {n} entries -> {_INDEX_PATH}")


if __name__ == "__main__":
    main()
