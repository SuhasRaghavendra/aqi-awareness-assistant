#!/usr/bin/env python3
"""
scripts/build_logbook_index.py
Regenerates docs/logbook/INDEX.md — a table of all logbook entries.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOGBOOK_DIR = ROOT / "docs" / "logbook"
INDEX_PATH = LOGBOOK_DIR / "INDEX.md"


def parse_entry(path: Path) -> dict:
    """Extract metadata from a logbook markdown file."""
    content = path.read_text(encoding="utf-8")
    data: dict = {"file": path.name, "path": str(path)}

    # Step number and title from first H1
    m = re.search(r"^# Step (\d+) — (.+)$", content, re.MULTILINE)
    if m:
        data["step"] = m.group(1)
        data["title"] = m.group(2).strip()
    else:
        data["step"] = path.stem.split("-")[0]
        data["title"] = path.stem

    # Date/time
    m = re.search(r"\*\*Date/time:\*\*\s*(.+?)(?:\s*\(|$)", content)
    data["date"] = m.group(1).strip() if m else ""

    # Phase
    m = re.search(r"\*\*Phase:\*\*\s*(\d+)", content)
    data["phase"] = m.group(1) if m else ""

    # Git commit
    m = re.search(r"\*\*Git commit\(s\):\*\*\s*`?([a-f0-9]+)`?", content)
    data["commit"] = m.group(1) if m else ""

    # Author
    m = re.search(r"\*\*Author:\*\*\s*(.+?)\s+\*\*Reviewer", content)
    data["author"] = m.group(1).strip() if m else ""

    return data


def build_index() -> None:
    """Scan all logbook entries and write INDEX.md."""
    LOGBOOK_DIR.mkdir(parents=True, exist_ok=True)

    entries = []
    for f in sorted(LOGBOOK_DIR.glob("*.md")):
        if f.name in {"INDEX.md", "_TEMPLATE.md"}:
            continue
        try:
            entries.append(parse_entry(f))
        except Exception as exc:
            print(f"Warning: could not parse {f.name}: {exc}")

    lines = [
        "# Logbook Index\n",
        "Auto-generated by `scripts/build_logbook_index.py`. Do not edit manually.\n",
        "",
        "| Step | Title | Phase | Date | Author | Commit | File |",
        "|------|-------|-------|------|--------|--------|------|",
    ]
    for e in entries:
        rel_path = e["file"]
        link = f"[{rel_path}]({rel_path})"
        lines.append(
            f"| {e.get('step','')} | {e.get('title','')} | {e.get('phase','')} | "
            f"{e.get('date','')[:10]} | {e.get('author','')} | "
            f"`{e.get('commit','')}` | {link} |"
        )

    INDEX_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"✅ Index rebuilt: {len(entries)} entries → {INDEX_PATH}")


if __name__ == "__main__":
    build_index()
